//comparação de objetos

let a = 5,b="5"

console.log(typeof a, typeof b) // number string

//igualdade e diferença

//igualdade
console.log(a == b) // true, pois compara o valor
//igualdade estrita
console.log(a === b) // false, pois compara o valor e o tipo

// diferença
console.log(a != b) // false, pois compara o valor
// diferença estrita
console.log(a !== b) // true, pois compara o valor e o tipo

//maior
console.log(a > b) // false
//menor
console.log(a < b) // false
//maior ou igual
console.log(a >= b) // true
//menor ou igual
console.log(a <= b) // true