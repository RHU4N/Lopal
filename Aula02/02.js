// Operadores
let a = 5,
  b = 2;

// Aritméticos
let soma = a + b; // soma
console.log("soma:", soma); // imprime o resultado da soma

let sub = a - b; // subtração
console.log("subtração:", sub); // imprime o resultado da subtração

let mult = a * b; // multiplicação
console.log("multiplicação:", mult); // imprime o resultado da multiplicação

let div = a / b; // divisão
console.log("divisão:", div); // imprime o resultado da divisão

let mod = a % b; // módulo (resto da divisão)
console.log("módulo:", mod); // imprime o resultado do módulo

let pot = a ** b; // potenciação
console.log("potenciação:", pot); // imprime o resultado da potenciação

